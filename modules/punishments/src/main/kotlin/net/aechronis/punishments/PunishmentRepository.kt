package net.aechronis.punishments

import java.nio.file.Files
import java.nio.file.Path
import java.sql.Connection
import java.sql.DriverManager
import java.sql.PreparedStatement
import java.sql.ResultSet
import java.sql.Statement
import java.sql.Types
import java.util.UUID

data class BlacklistGroup(
    val name: String,
    val reason: String,
    val staffName: String,
    val createdAt: Long,
)

/** Embedded H2 store. IPs are kept for enforcement only and never leave this class except for IP checks. */
class PunishmentRepository(
    databasePath: Path = Path.of("punishments", "punishments").toAbsolutePath().normalize(),
) {
    private val url: String

    init {
        databasePath.parent?.let(Files::createDirectories)
        url = "jdbc:h2:file:${databasePath.toString().replace('\\', '/')};DB_CLOSE_ON_EXIT=FALSE;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=5000"
        connect { connection ->
            connection.createStatement().use { statement ->
                statement.execute(
                    """
                    CREATE TABLE IF NOT EXISTS players (
                        uuid VARCHAR(36) PRIMARY KEY,
                        name VARCHAR(16) NOT NULL,
                        name_lower VARCHAR(16) NOT NULL,
                        last_ip VARCHAR(45),
                        last_seen BIGINT NOT NULL
                    )
                    """.trimIndent(),
                )
                statement.execute("CREATE INDEX IF NOT EXISTS idx_players_name ON players(name_lower)")
                statement.execute(
                    """
                    CREATE TABLE IF NOT EXISTS punishments (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        offence VARCHAR(36) NOT NULL,
                        uuid VARCHAR(36) NOT NULL,
                        name VARCHAR(16) NOT NULL,
                        type VARCHAR(16) NOT NULL,
                        category VARCHAR(32),
                        reason VARCHAR(512) NOT NULL,
                        staff_uuid VARCHAR(36),
                        staff_name VARCHAR(32) NOT NULL,
                        created_at BIGINT NOT NULL,
                        expires_at BIGINT,
                        ip VARCHAR(45),
                        revoked_at BIGINT,
                        revoked_by VARCHAR(32),
                        revoke_reason VARCHAR(512)
                    )
                    """.trimIndent(),
                )
                statement.execute("ALTER TABLE punishments ADD COLUMN IF NOT EXISTS evidence VARCHAR(4000)")
                // Infraction sheet rows replaced the old categories, whose column is kept for old records only.
                statement.execute("ALTER TABLE punishments ADD COLUMN IF NOT EXISTS infraction VARCHAR(32)")
                statement.execute("ALTER TABLE punishments ADD COLUMN IF NOT EXISTS strike INT")
                statement.execute("ALTER TABLE punishments ADD COLUMN IF NOT EXISTS anonymous BOOLEAN DEFAULT FALSE NOT NULL")
                statement.execute("ALTER TABLE punishments ADD COLUMN IF NOT EXISTS silent BOOLEAN DEFAULT FALSE NOT NULL")
                statement.execute("ALTER TABLE punishments ADD COLUMN IF NOT EXISTS incomplete BOOLEAN DEFAULT FALSE NOT NULL")
                statement.execute("ALTER TABLE punishments ADD COLUMN IF NOT EXISTS discord_message BIGINT")
                statement.execute("CREATE INDEX IF NOT EXISTS idx_punishments_offence ON punishments(offence)")
                statement.execute("CREATE INDEX IF NOT EXISTS idx_punishments_uuid ON punishments(uuid, created_at DESC)")
                statement.execute("CREATE INDEX IF NOT EXISTS idx_punishments_created ON punishments(created_at DESC)")
                statement.execute("CREATE INDEX IF NOT EXISTS idx_punishments_ip ON punishments(ip)")
                statement.execute(
                    """
                    CREATE TABLE IF NOT EXISTS blacklist_groups (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(64) NOT NULL,
                        name_lower VARCHAR(64) NOT NULL UNIQUE,
                        reason VARCHAR(512) NOT NULL,
                        staff_name VARCHAR(32) NOT NULL,
                        created_at BIGINT NOT NULL
                    )
                    """.trimIndent(),
                )
                statement.execute(
                    """
                    CREATE TABLE IF NOT EXISTS strikes (
                        uuid VARCHAR(36) NOT NULL,
                        infraction VARCHAR(32) NOT NULL,
                        count INT NOT NULL,
                        PRIMARY KEY (uuid, infraction)
                    )
                    """.trimIndent(),
                )
                statement.execute(
                    """
                    CREATE TABLE IF NOT EXISTS ip_history (
                        uuid VARCHAR(36) NOT NULL,
                        ip VARCHAR(45) NOT NULL,
                        last_seen BIGINT NOT NULL,
                        PRIMARY KEY (uuid, ip)
                    )
                    """.trimIndent(),
                )
                statement.execute("CREATE INDEX IF NOT EXISTS idx_ip_history_ip ON ip_history(ip)")
                // Seeds the history with the IPs known from before it existed.
                statement.execute(
                    "INSERT INTO ip_history (uuid, ip, last_seen) SELECT uuid, last_ip, last_seen FROM players p " +
                        "WHERE last_ip IS NOT NULL AND NOT EXISTS (SELECT 1 FROM ip_history h WHERE h.uuid = p.uuid AND h.ip = p.last_ip)",
                )
            }
        }
    }

    fun remember(
        uuid: UUID,
        name: String,
        ip: String?,
    ) = transaction { connection ->
        val now = System.currentTimeMillis()
        connection
            .prepareStatement(
                "MERGE INTO players (uuid, name, name_lower, last_ip, last_seen) KEY(uuid) VALUES (?, ?, ?, ?, ?)",
            ).use { statement ->
                statement.setString(1, uuid.toString())
                statement.setString(2, name)
                statement.setString(3, name.lowercase())
                statement.setString(4, ip)
                statement.setLong(5, now)
                statement.executeUpdate()
            }
        if (ip != null) {
            connection.prepareStatement("MERGE INTO ip_history (uuid, ip, last_seen) KEY(uuid, ip) VALUES (?, ?, ?)").use { statement ->
                statement.setString(1, uuid.toString())
                statement.setString(2, ip)
                statement.setLong(3, now)
                statement.executeUpdate()
            }
        }
    }

    /** Other accounts that ever joined from one of the player's IPs, most recently seen first. Never returns the IPs. */
    internal fun alts(uuid: UUID): List<KnownPlayer> =
        connect { connection ->
            val sql =
                "SELECT p.uuid, p.name FROM players p WHERE p.uuid <> ? AND p.uuid IN " +
                    "(SELECT b.uuid FROM ip_history a JOIN ip_history b ON a.ip = b.ip WHERE a.uuid = ?) ORDER BY p.last_seen DESC"
            connection.prepareStatement(sql).use { statement ->
                statement.setString(1, uuid.toString())
                statement.setString(2, uuid.toString())
                statement.executeQuery().use { rows ->
                    buildList { while (rows.next()) add(KnownPlayer(UUID.fromString(rows.getString(1)), rows.getString(2), null)) }
                }
            }
        }

    /** Strike count per infraction row; rows at zero are left out. */
    fun strikes(uuid: UUID): Map<Infraction, Int> =
        connect { connection ->
            connection.prepareStatement("SELECT infraction, count FROM strikes WHERE uuid = ? AND count > 0").use { statement ->
                statement.setString(1, uuid.toString())
                statement.executeQuery().use { rows ->
                    buildMap { while (rows.next()) Infraction.parse(rows.getString(1))?.let { put(it, rows.getInt(2)) } }
                }
            }
        }

    /** Adds [delta] strikes to the row, never going below zero, and returns the new count. */
    fun addStrikes(
        uuid: UUID,
        infraction: Infraction,
        delta: Int,
    ): Int =
        transaction { connection ->
            val current =
                connection.prepareStatement("SELECT count FROM strikes WHERE uuid = ? AND infraction = ? FOR UPDATE").use { statement ->
                    statement.setString(1, uuid.toString())
                    statement.setString(2, infraction.name)
                    statement.executeQuery().use { rows -> if (rows.next()) rows.getInt(1) else 0 }
                }
            val next = (current + delta).coerceAtLeast(0)
            connection.prepareStatement("MERGE INTO strikes (uuid, infraction, count) KEY(uuid, infraction) VALUES (?, ?, ?)").use {
                it.setString(1, uuid.toString())
                it.setString(2, infraction.name)
                it.setInt(3, next)
                it.executeUpdate()
            }
            next
        }

    /** Takes one strike off every player in the [infractions] rows. Returns how many rows went down. */
    fun decayStrikes(infractions: Collection<Infraction>): Int {
        if (infractions.isEmpty()) return 0
        val names = infractions.joinToString { "'${it.name}'" }
        return connect { connection ->
            connection.createStatement().use {
                it.executeUpdate(
                    "UPDATE strikes SET count = count - 1 WHERE count > 0 AND infraction IN ($names)",
                )
            }
        }
    }

    /** Adds a never-joined player (punished by name) so the website lookup can find them. */
    fun know(
        uuid: UUID,
        name: String,
    ) = connect { connection ->
        connection
            .prepareStatement(
                "INSERT INTO players (uuid, name, name_lower, last_seen) SELECT ?, ?, ?, 0 WHERE NOT EXISTS (SELECT 1 FROM players WHERE uuid = ?)",
            ).use { statement ->
                statement.setString(1, uuid.toString())
                statement.setString(2, name)
                statement.setString(3, name.lowercase())
                statement.setString(4, uuid.toString())
                statement.executeUpdate()
            }
    }

    /** By UUID or (case-insensitive) last known name. */
    internal fun findPlayer(query: String): KnownPlayer? =
        connect { connection ->
            val uuid = runCatching { UUID.fromString(query) }.getOrNull()
            val sql =
                if (uuid != null) {
                    "SELECT uuid, name, last_ip FROM players WHERE uuid = ?"
                } else {
                    "SELECT uuid, name, last_ip FROM players WHERE name_lower = ? ORDER BY last_seen DESC LIMIT 1"
                }
            connection.prepareStatement(sql).use { statement ->
                statement.setString(1, uuid?.toString() ?: query.lowercase())
                statement.executeQuery().use { rows ->
                    if (rows.next()) KnownPlayer(UUID.fromString(rows.getString(1)), rows.getString(2), rows.getString(3)) else null
                }
            }
        }

    /** Inserts all records of one offence atomically; IP bans store [ip]. */
    fun insert(
        drafts: List<Record>,
        ip: String?,
    ): List<Record> =
        transaction { connection ->
            drafts.map { draft ->
                connection
                    .prepareStatement(
                        """
                        INSERT INTO punishments
                            (offence, uuid, name, type, infraction, reason, staff_uuid, staff_name, created_at, expires_at, ip, evidence,
                             strike, anonymous, silent, incomplete)
                        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                        """.trimIndent(),
                        Statement.RETURN_GENERATED_KEYS,
                    ).use { statement ->
                        statement.setString(1, draft.offence)
                        statement.setString(2, draft.uuid.toString())
                        statement.setString(3, draft.name)
                        statement.setString(4, draft.type.name)
                        statement.setString(5, draft.infraction?.name)
                        statement.setString(6, draft.reason.take(512))
                        statement.setString(7, draft.staffUuid?.toString())
                        statement.setString(8, draft.staffName)
                        statement.setLong(9, draft.createdAt)
                        statement.setNullableLong(10, draft.expiresAt)
                        statement.setString(11, ip.takeIf { draft.type == Type.IP_BAN })
                        statement.setString(12, draft.evidence?.take(4000))
                        if (draft.strike == null) statement.setNull(13, Types.INTEGER) else statement.setInt(13, draft.strike)
                        statement.setBoolean(14, draft.anonymous)
                        statement.setBoolean(15, draft.silent)
                        statement.setBoolean(16, draft.incomplete)
                        statement.executeUpdate()
                        statement.generatedKeys.use { keys ->
                            keys.next()
                            draft.copy(id = keys.getLong(1))
                        }
                    }
            }
        }

    fun revoke(
        uuid: UUID,
        types: Set<Type>,
        by: String,
        reason: String,
    ): List<Record> = revokeWhere("uuid = ? AND type IN (${types.joinToString { "'${it.name}'" }})", uuid.toString(), by, reason)

    /** Lifts every active record of [offence], including its warning. */
    fun revokeOffence(
        offence: String,
        by: String,
        reason: String,
    ): List<Record> = revokeWhere("offence = ?", offence, by, reason)

    /** Every record of [offence], oldest first. */
    fun offence(offence: String): List<Record> = connect { query(it, "SELECT * FROM punishments WHERE offence = ? ORDER BY id", offence) }

    /** The newest offence in [infraction] that still has something to lift. */
    fun latestOffence(
        uuid: UUID,
        infraction: Infraction,
    ): String? =
        connect { connection ->
            // Expired punishments have nothing left to lift.
            val sql =
                "SELECT offence FROM punishments WHERE uuid = ? AND infraction = ? AND revoked_at IS NULL " +
                    "AND (expires_at IS NULL OR expires_at > ?) ORDER BY created_at DESC LIMIT 1"
            connection.prepareStatement(sql).use { statement ->
                statement.setString(1, uuid.toString())
                statement.setString(2, infraction.name)
                statement.setLong(3, System.currentTimeMillis())
                statement.executeQuery().use { rows -> if (rows.next()) rows.getString(1) else null }
            }
        }

    fun setDiscordMessage(
        offence: String,
        message: Long,
    ) = update("UPDATE punishments SET discord_message = ? WHERE offence = ?") {
        it.setLong(1, message)
        it.setString(2, offence)
    }

    /** Returns whether the offence was still waiting on a nuke or rollback. */
    fun clearIncomplete(offence: String): Boolean =
        update("UPDATE punishments SET incomplete = FALSE WHERE offence = ? AND incomplete") { it.setString(1, offence) } > 0

    private fun update(
        sql: String,
        bind: (PreparedStatement) -> Unit,
    ): Int =
        connect { connection ->
            connection.prepareStatement(sql).use {
                bind(it)
                it.executeUpdate()
            }
        }

    /** Appends [text] to the evidence of every record in [offence] and returns those records. */
    fun addEvidence(
        offence: String,
        text: String,
    ): List<Record> =
        transaction { connection ->
            val sql = "UPDATE punishments SET evidence = LEFT(CONCAT_WS(CHAR(10), evidence, ?), 4000) WHERE offence = ?"
            connection.prepareStatement(sql).use { statement ->
                statement.setString(1, text)
                statement.setString(2, offence)
                statement.executeUpdate()
            }
            query(connection, "SELECT * FROM punishments WHERE offence = ? ORDER BY id", offence)
        }

    /** Every active iteration ban, plus the IP bans issued in the same offence (ban evasion). */
    fun revokeIterationBans(
        by: String,
        reason: String,
    ): List<Record> {
        val paired = "SELECT offence FROM punishments WHERE type = '${Type.ITERATION_BAN.name}' AND revoked_at IS NULL"
        return revokeWhere("(type = ? OR (type = '${Type.IP_BAN.name}' AND offence IN ($paired)))", Type.ITERATION_BAN.name, by, reason)
    }

    private fun revokeWhere(
        filter: String,
        value: String,
        by: String,
        reason: String,
    ): List<Record> =
        transaction { connection ->
            val now = System.currentTimeMillis()
            val active = "$filter AND revoked_at IS NULL AND (expires_at IS NULL OR expires_at > ?)"
            val targets = query(connection, "SELECT * FROM punishments WHERE $active", value, now)
            val sql = "UPDATE punishments SET revoked_at = ?, revoked_by = ?, revoke_reason = ? WHERE id = ?"
            connection.prepareStatement(sql).use { update ->
                targets.forEach { record ->
                    update.setLong(1, now)
                    update.setString(2, by)
                    update.setString(3, reason.take(512))
                    update.setLong(4, record.id)
                    update.addBatch()
                }
                update.executeBatch()
            }
            targets.map { it.copy(revokedAt = now, revokedBy = by, revokeReason = reason) }
        }

    fun record(id: Long): Record? = connect { query(it, "SELECT * FROM punishments WHERE id = ?", id).firstOrNull() }

    /** Last known names starting with [prefix], most recently seen first. */
    fun names(
        prefix: String,
        limit: Int,
    ): List<String> =
        connect { connection ->
            val sql = "SELECT name FROM players WHERE name_lower LIKE ? ORDER BY last_seen DESC LIMIT ?"
            connection.prepareStatement(sql).use { statement ->
                statement.setString(1, prefix.lowercase().replace("_", "\\_").replace("%", "\\%") + "%")
                statement.setInt(2, limit)
                statement.executeQuery().use { rows -> buildList { while (rows.next()) add(rows.getString(1)) } }
            }
        }

    /** Every record for the player, newest first. */
    fun history(uuid: UUID): List<Record> =
        connect { query(it, "SELECT * FROM punishments WHERE uuid = ? ORDER BY created_at DESC, id DESC", uuid.toString()) }

    fun active(uuid: UUID): List<Record> = history(uuid).filter { it.active() }

    fun activeIpBan(ip: String): Record? =
        connect { connection ->
            query(
                connection,
                "SELECT * FROM punishments WHERE ip = ? AND type = 'IP_BAN' AND revoked_at IS NULL AND (expires_at IS NULL OR expires_at > ?) LIMIT 1",
                ip,
                System.currentTimeMillis(),
            ).firstOrNull()
        }

    fun recent(limit: Int): List<Record> =
        connect { query(it, "SELECT * FROM punishments ORDER BY created_at DESC, id DESC LIMIT ?", limit) }

    fun blacklisted(): List<Record> =
        connect { connection ->
            query(
                connection,
                "SELECT * FROM punishments WHERE type = 'BLACKLIST' AND revoked_at IS NULL ORDER BY created_at DESC",
            )
        }

    fun createGroup(
        name: String,
        reason: String,
        staffName: String,
    ): Boolean =
        connect { connection ->
            connection
                .prepareStatement(
                    "INSERT INTO blacklist_groups (name, name_lower, reason, staff_name, created_at) SELECT ?, ?, ?, ?, ? " +
                        "WHERE NOT EXISTS (SELECT 1 FROM blacklist_groups WHERE name_lower = ?)",
                ).use { statement ->
                    statement.setString(1, name)
                    statement.setString(2, name.lowercase())
                    statement.setString(3, reason.take(512))
                    statement.setString(4, staffName)
                    statement.setLong(5, System.currentTimeMillis())
                    statement.setString(6, name.lowercase())
                    statement.executeUpdate() == 1
                }
        }

    fun deleteGroup(name: String): Boolean =
        connect { connection ->
            connection.prepareStatement("DELETE FROM blacklist_groups WHERE name_lower = ?").use { statement ->
                statement.setString(1, name.lowercase())
                statement.executeUpdate() == 1
            }
        }

    fun groups(): List<BlacklistGroup> =
        connect { connection ->
            connection.createStatement().use { statement ->
                val sql = "SELECT name, reason, staff_name, created_at FROM blacklist_groups ORDER BY name_lower"
                statement.executeQuery(sql).use { rows ->
                    buildList {
                        while (rows.next()) {
                            add(
                                BlacklistGroup(rows.getString(1), rows.getString(2), rows.getString(3), rows.getLong(4)),
                            )
                        }
                    }
                }
            }
        }

    private fun query(
        connection: Connection,
        sql: String,
        vararg params: Any,
    ): List<Record> =
        connection.prepareStatement(sql).use { statement ->
            params.forEachIndexed { index, param ->
                when (param) {
                    is String -> statement.setString(index + 1, param)
                    is Long -> statement.setLong(index + 1, param)
                    is Int -> statement.setInt(index + 1, param)
                    else -> error("Unsupported parameter ${param.javaClass}")
                }
            }
            statement.executeQuery().use { rows -> buildList { while (rows.next()) add(rows.toRecord()) } }
        }

    private fun ResultSet.toRecord() =
        Record(
            id = getLong("id"),
            offence = getString("offence"),
            uuid = UUID.fromString(getString("uuid")),
            name = getString("name"),
            type = Type.valueOf(getString("type")),
            infraction = Infraction.parse(getString("infraction")),
            legacyCategory = LEGACY_CATEGORIES[getString("category")],
            reason = getString("reason"),
            staffUuid = getString("staff_uuid")?.let(UUID::fromString),
            staffName = getString("staff_name"),
            createdAt = getLong("created_at"),
            expiresAt = getNullableLong("expires_at"),
            revokedAt = getNullableLong("revoked_at"),
            revokedBy = getString("revoked_by"),
            revokeReason = getString("revoke_reason"),
            evidence = getString("evidence"),
            strike = getInt("strike").takeUnless { wasNull() },
            anonymous = getBoolean("anonymous"),
            silent = getBoolean("silent"),
            incomplete = getBoolean("incomplete"),
            discordMessage = getNullableLong("discord_message"),
        )

    private companion object {
        /** Labels of the categories used before the infraction sheet, still stored on old records. */
        val LEGACY_CATEGORIES =
            mapOf(
                "MINOR_CHAT" to "Minor chat violation",
                "MAJOR_CHAT" to "Major chat violation",
                "MINOR_EXPLOIT" to "Minor exploit",
                "MAJOR_EXPLOIT" to "Major exploit",
                "ILLEGAL_CLIENT" to "Illegal client or modification",
                "BAN_EVASION" to "Ban evasion",
            )
    }

    private fun ResultSet.getNullableLong(column: String): Long? = getLong(column).takeUnless { wasNull() }

    private fun PreparedStatement.setNullableLong(
        index: Int,
        value: Long?,
    ) = if (value == null) setNull(index, Types.BIGINT) else setLong(index, value)

    /** DB_CLOSE_DELAY=-1 keeps the database open between queries, so close it explicitly to flush it. */
    fun close() = connect { connection -> connection.createStatement().use { it.execute("SHUTDOWN") } }

    private fun <T> connect(block: (Connection) -> T): T = DriverManager.getConnection(url).use(block)

    private fun <T> transaction(block: (Connection) -> T): T =
        connect { connection ->
            connection.autoCommit = false
            try {
                block(connection).also { connection.commit() }
            } catch (error: Throwable) {
                connection.rollback()
                throw error
            }
        }
}
